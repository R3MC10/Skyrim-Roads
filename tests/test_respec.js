// Respec: 10,000 gold puts every perk point and every Health/Magicka/Stamina choice back in the pool.
const fs = require("fs"), vm = require("vm"), path = require("path");
const W = process.env.W || path.join(__dirname, "../game/");
const c = vm.createContext({ console, Math, Date, JSON, Object, Array, Set, Map });
for (const f of ["data.js", "world.js", "terrain.js", "formulas.js", "perks.js", "respec.js", "powers.js", "engine.js"])
  vm.runInContext(fs.readFileSync(W + f, "utf8").replace(/^const (\w+) =/m, "var $1 ="), c);
let fails = 0;
const ok = (v, m) => { if (!v) { fails++; console.log("FAIL", m); } };
vm.runInContext(`var __s = G.newSave("t1", "Test", "nord");`, c);
const s = c.__s, { G, PERKS, RESPEC } = c;
ok(RESPEC.can(s) === "Nothing to take back yet.", "a fresh hero has nothing to respec");
ok(RESPEC.panel(s) === "", "no panel for a fresh hero");
s.level = 6; s.pendingLevels = 5;
G.levelUp(s, "health"); G.levelUp(s, "health"); G.levelUp(s, "stamina");
for (const k of Object.keys(s.skills)) s.skills[k].lvl = 100;
const first = Object.keys(PERKS.BY_ID).find((id) => !PERKS.BY_ID[id].needs.length);
PERKS.take(s, first);
const hp0 = G.maxHealth(s), left0 = PERKS.pointsLeft(s);
ok(left0 === 4 && s.pendingLevels === 2, "set-up: 1 perk taken, 3 choices made");
s.gold = 9999; ok(/10,000|10000/.test(RESPEC.can(s)), "not enough gold: " + RESPEC.can(s));
ok(/disabled/.test(RESPEC.panel(s)), "button disabled when short of gold");
s.gold = 12000;
ok(RESPEC.can(s) === null, "can respec with gold");
RESPEC.arm(true); ok(/Yes, respec/.test(RESPEC.panel(s)), "asks to confirm first");
const msg = RESPEC.run(s);
ok(/1 perk point and 3 level-up choices/.test(msg), "message: " + msg);
ok(s.gold === 2000, "costs 10,000 gold");
ok(PERKS.pointsLeft(s) === 5 && Object.keys(s.perks).length === 0, "all perk points back");
ok(s.pendingLevels === 5 && s.hpBonus === 0 && s.spBonus === 0 && s.mpBonus === 0, "all level-up choices back");
ok(G.maxHealth(s) === hp0 - 20 && s.health <= G.maxHealth(s), "health falls back with the bonus");
ok(RESPEC.can(s) === "Nothing to take back yet.", "nothing left to take back");
G.levelUp(s, "magicka"); ok(s.mpBonus === 10 && s.pendingLevels === 4, "choices can be spent again");
console.log(fails ? `FAILED ${fails}` : "respec ok");
process.exit(fails ? 1 : 0);
