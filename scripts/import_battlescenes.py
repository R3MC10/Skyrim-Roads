"""Import a Roads of the North battle-scene pack into the game.
Usage: python3 scripts/import_battlescenes.py <extracted pack folder>   (needs Pillow)

Reads scene-manifest.json from the pack and writes, flat into game/ (the build copies game/ flat):
  bs-<scene>.webp        backdrop plates, 1480×680 (from 1850×850; the stage is at most 1040 px wide on a phone)
  bsf-<name>.webp        transparent foreground strips, 1480 px wide
  bsp-<name>.webp        transparent props, lights and effects, at most 320 px on the long side
  bscdata.js             BSCENE_DATA: scenes (layers, placement, motion), terrain → scene, arena, frames, planes
Also copies the pack's location-index.csv to tests/battlescene-locations.csv (test_battlescene.js checks the
game's own resolver against it). Scene coordinates stay normalised, so resizing changes nothing on screen."""
import json, os, sys, shutil
from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else "."
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = os.path.join(ROOT, "game")
m = json.load(open(os.path.join(SRC, "scene-manifest.json"), encoding="utf-8"))

def base(path): return os.path.splitext(os.path.basename(path))[0]
def fg_key(path):
    b = base(path)
    return "bsf-" + ("mine" if b == "embershard-mine" else b.replace("front-", ""))
def bg_key(scene): return "bs-" + scene["id"]
def prop_key(path): return "bsp-" + base(path)

def save(src, key, size=None, longest=None, q=80):
    im = Image.open(os.path.join(SRC, src))
    im = im.convert("RGBA" if im.mode in ("RGBA", "LA", "P") else "RGB")
    if size: im = im.resize(size, Image.LANCZOS)
    if longest and max(im.size) > longest:
        k = longest / max(im.size); im = im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)
    out = os.path.join(GAME, key + ".webp")
    im.save(out, "WEBP", quality=q, method=6, alpha_quality=90)
    return os.path.getsize(out)

r4 = lambda v: round(v, 4)
scenes, done, total = {}, set(), 0
for s in m["scenes"]:
    bk, fk = bg_key(s), fg_key(s["foreground"]["file"])
    if bk not in done: total += save(s["background"], bk, size=(1480, 680), q=78); done.add(bk)
    if fk not in done:
        im = Image.open(os.path.join(SRC, s["foreground"]["file"])); h = round(im.height * 1480 / im.width)
        total += save(s["foreground"]["file"], fk, size=(1480, h), q=82); done.add(fk)
    els = []
    for e in s["elements"]:
        pk = prop_key(e["file"])
        if pk not in done: total += save(e["file"], pk, longest=320, q=82); done.add(pk)
        o = {"k": pk, "x": r4(e["x"]), "y": r4(e["y"]), "h": r4(e["height"]), "a": [r4(e["anchor"][0]), r4(e["anchor"][1])], "p": e["plane"]}
        for src, dst in (("width", "w"), ("opacity", "o"), ("blend", "b"), ("motion", "m")):
            if e.get(src) is not None: o[dst] = r4(e[src]) if isinstance(e[src], float) else e[src]
        if e.get("light"): o["l"] = 1
        els.append(o)
    scenes[s["id"]] = {"title": s["title"], "group": s["group"], "scene": s["currentScene"], "bg": bk, "fg": fk, "fgH": r4(s["foreground"]["height"]), "els": els}

data = {"source": f'{m["repository"]}@{m["revision"][:7]}', "frames": m["frames"], "planes": m["planes"], "terrain": m["terrain"], "arena": m["arena"]["art"], "scenes": scenes}
js = ("/* Battle-scene data (generated by scripts/import_battlescenes.py from the scene pack's scene-manifest.json; do not edit by hand).\n"
      "   battlescene.js reads it. Keys are picture names next to index.html (bs-* backdrops, bsf-* foreground strips, bsp-* props). */\n"
      "const BSCENE_DATA = " + json.dumps(data, separators=(",", ":"), ensure_ascii=False) + ";\n"
      'if (typeof module !== "undefined") module.exports = BSCENE_DATA;\n')
open(os.path.join(GAME, "bscdata.js"), "w", encoding="utf-8").write(js)
shutil.copy(os.path.join(SRC, "location-index.csv"), os.path.join(ROOT, "tests", "battlescene-locations.csv"))
print(f"{len(scenes)} scenes, {len(done)} pictures, {total / 1048576:.2f} MB; bscdata.js {len(js) / 1024:.1f} KB")
